#!/usr/bin/env node
/**
 * Scans public/work/ and writes src/content/media.generated.ts.
 *
 * The point is that adding a video is a file-drop, not a code edit: name the
 * files after a project's slug, run `npm run media`, and the card picks them
 * up. A slug with only a poster renders a still; a slug with clips renders a
 * hover-to-play loop. Nothing is wired by hand.
 */
import { readdirSync, writeFileSync, statSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mediaDir = join(root, "public", "work");
const outFile = join(root, "src", "content", "media.generated.ts");

/* Ordered best-first: browsers take the first type they can decode, and AV1 is
   roughly 30-50% smaller than H.264 at the same quality. */
const VIDEO_TYPES = [
  { suffix: ".av1.mp4", type: 'video/mp4; codecs="av01.0.05M.08"' },
  { suffix: ".webm", type: "video/webm" },
  { suffix: ".mp4", type: "video/mp4" },
];
const POSTER_EXTS = [".avif", ".webp", ".jpg", ".jpeg", ".png", ".svg"];

/* Budgets, enforced loudly rather than left to discipline. */
const WARN_CLIP_BYTES = 2.5 * 1024 * 1024;
const FAIL_CLIP_BYTES = 10 * 1024 * 1024;
const WARN_TOTAL_BYTES = 10 * 1024 * 1024;

const mb = (n) => `${(n / 1024 / 1024).toFixed(1)} MB`;

mkdirSync(mediaDir, { recursive: true });

const files = readdirSync(mediaDir).filter((f) => {
  try {
    return statSync(join(mediaDir, f)).isFile() && !f.startsWith(".");
  } catch {
    return false;
  }
});

/* Longest suffix first, so "clip.av1.mp4" is not mistaken for slug "clip.av1". */
const sortedVideo = [...VIDEO_TYPES].sort(
  (a, b) => b.suffix.length - a.suffix.length,
);

const slugs = new Map();
const problems = [];
let totalBytes = 0;

for (const file of files) {
  const path = join(mediaDir, file);
  const size = statSync(path).size;

  const poster = POSTER_EXTS.find((e) => file.toLowerCase().endsWith(e));
  const video = sortedVideo.find((v) => file.toLowerCase().endsWith(v.suffix));

  if (!poster && !video) continue;

  const slug = file.slice(0, file.length - (video ? video.suffix : poster).length);
  if (!slugs.has(slug)) slugs.set(slug, { poster: null, sources: [] });
  const entry = slugs.get(slug);

  if (video) {
    totalBytes += size;
    if (size > FAIL_CLIP_BYTES) {
      problems.push(`FAIL  ${file} is ${mb(size)} — over the ${mb(FAIL_CLIP_BYTES)} hard limit.`);
    } else if (size > WARN_CLIP_BYTES) {
      problems.push(`warn  ${file} is ${mb(size)} — aim under ${mb(WARN_CLIP_BYTES)} per clip.`);
    }
    entry.sources.push({ src: `/work/${file}`, type: video.type, size });
  } else {
    /* Prefer the most efficient poster format when several exist. */
    const rank = POSTER_EXTS.indexOf(poster);
    if (!entry.poster || rank < entry.poster.rank) {
      entry.poster = { src: `/work/${file}`, rank };
    }
  }
}

const manifest = {};
for (const [slug, entry] of [...slugs.entries()].sort()) {
  if (!entry.poster) {
    if (entry.sources.length) {
      problems.push(
        `FAIL  "${slug}" has video but no poster. The poster is what loads first — without it the card is blank until playback starts.`,
      );
    }
    continue;
  }
  entry.sources.sort(
    (a, b) =>
      sortedVideo.findIndex((v) => a.type === v.type) -
      sortedVideo.findIndex((v) => b.type === v.type),
  );
  manifest[slug] = {
    poster: entry.poster.src,
    sources: entry.sources.map(({ src, type }) => ({ src, type })),
  };
}

if (totalBytes > WARN_TOTAL_BYTES) {
  problems.push(
    `warn  ${mb(totalBytes)} of video committed. Past ~${mb(WARN_TOTAL_BYTES)}, move clips to a streaming host (see public/work/README.md).`,
  );
}

const body = `/* GENERATED by scripts/build-media-manifest.mjs — do not edit.
   Run \`npm run media\` after adding or removing files in public/work/. */

export type MediaEntry = {
  readonly poster: string;
  readonly sources: readonly { readonly src: string; readonly type: string }[];
};

export const mediaManifest: Readonly<Record<string, MediaEntry>> = ${JSON.stringify(manifest, null, 2)} as const;
`;

writeFileSync(outFile, body);

const clips = Object.values(manifest).filter((m) => m.sources.length).length;
console.log(
  `media: ${Object.keys(manifest).length} slug(s), ${clips} with video, ${mb(totalBytes)} of clips`,
);
for (const p of problems) console.log("  " + p);

if (problems.some((p) => p.startsWith("FAIL"))) {
  console.error("\nmedia manifest failed — fix the items above.");
  process.exit(1);
}
